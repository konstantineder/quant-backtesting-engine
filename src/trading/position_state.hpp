#pragma once

// Signed position state for one universe slot.
//
// The instrument is not stored: positions live in a dense vector indexed by
// InstrumentIndex, so the slot already identifies the instrument.
//
// Conventions:
//   * `quantity` is signed -- positive long, negative short.
//   * `averagePrice` is the weighted average UNIT entry price of the
//     currently open lot, and is exactly 0 while flat.
//   * `realizedPnL` is GROSS of fees and already scaled by the contract
//     multiplier. Fees are cash-side only and are tracked by the Account,
//     which keeps them from being counted twice.
class PositionState {
public:
    PositionState() = default;

    PositionState(
        double quantity,
        double average_price,
        double realized_pnl
    );

    double quantity() const noexcept { return quantity_; }
    double averagePrice() const noexcept { return average_price_; }
    double realizedPnL() const noexcept { return realized_pnl_; }

    bool isFlat() const noexcept { return quantity_ == 0.0; }
    bool isLong() const noexcept { return quantity_ > 0.0; }
    bool isShort() const noexcept { return quantity_ < 0.0; }

    // Applies a signed fill quantity at a unit price and returns the
    // realized PnL generated by this fill alone (0 when the fill only
    // opens or increases the position).
    //
    // Handles opening, increasing, partial closes, full closes and
    // reversals. On a reversal the closing leg realizes PnL and the
    // remaining quantity opens at the fill price.
    //
    // Strong exception safety: validates a fully computed candidate state
    // before committing anything.
    double applyFill(
        double quantity,
        double price,
        double contract_multiplier
    );

private:
    static void validate(
        double quantity,
        double average_price,
        double realized_pnl
    );

    double quantity_ = 0.0;
    double average_price_ = 0.0;
    double realized_pnl_ = 0.0;
};
